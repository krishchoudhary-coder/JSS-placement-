export const fieldLabel = (field: string) =>
  field
    .replace(/_/g, " ")
    .replace(/\b(ai|ml|esg|tam|sam|som|cac|ltv|ceo|url|r&d)\b/gi, (word) =>
      word.toUpperCase(),
    )
    .replace(/\b\w/g, (letter) => letter.toUpperCase())

export const sectionId = (title: string) =>
  title
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
