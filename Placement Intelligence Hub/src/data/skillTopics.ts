export const bloomForScore = (score: number) => {
  if (score <= 2) return "CU"
  if (score <= 4) return "AP"
  if (score <= 6) return "AS"
  if (score <= 8) return "EV"
  return "CR"
}

export const criticalityForScore = (score: number) =>
  score >= 7 ? "Critical" : score >= 5 ? "Important" : "Baseline"
